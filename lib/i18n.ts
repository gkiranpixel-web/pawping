// Lightweight, dependency-free i18n for the finder-facing public page
// (`/c/[token]`) only. The owner dashboard stays English — the owner
// chose to use TagPing in English; the person who finds their lost item
// on the street may not speak it, which is the actual gap this closes.
//
// Auto-detects the visitor's browser language, with a manual switcher as
// an escape hatch (auto-detection is a good guess, not a guarantee).

export interface Locale {
  code: string;
  label: string;
}

export const LOCALES: Locale[] = [
  {code:"en", label:"English"},
  {code:"es", label:"Español"},
  {code:"fr", label:"Français"},
  {code:"de", label:"Deutsch"},
  {code:"hi", label:"हिन्दी"},
];

export function detectLocale(): string {
  if(typeof navigator==="undefined")return "en";
  const codes=LOCALES.map(l=>l.code);
  const langs=navigator.languages&&navigator.languages.length?navigator.languages:[navigator.language||"en"];
  for(const l of langs){
    const short=String(l).slice(0,2).toLowerCase();
    if(codes.includes(short))return short;
  }
  return "en";
}

export type TranslateFn = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(locale: string): TranslateFn {
  const dict: Record<string, string> = STRINGS[locale] || STRINGS.en;
  return (key, vars) => {
    let s = dict[key] ?? STRINGS.en[key] ?? key;
    if (vars) Object.keys(vars).forEach(k => { s = s.replaceAll(`{${k}}`, String(vars[k])); });
    return s;
  };
}

